/** 从回复文本统计"上次发了几条消息"（供条数轮换提示用） */
export function countReplyLines(text: string): number {
  return text
    .split(/\r?\n/)
    .map((s) => s.trim())
    .filter(Boolean).length;
}

/**
 * 条数轮换锚点：把角色最近几轮 assistant 回复的条数列出来塞进 system，
 * 模型看不到自己的"发送行为"，只能靠这个显式提醒才能做到"相邻两轮条数不同"。
 */
export function buildCountHint(recentCounts: number[]): string {
  if (!recentCounts.length) return "";
  return (
    "\n【你的发送节奏】你最近几轮分别发了 " +
    recentCounts.map((c) => `${c}条`).join("、") +
    " 的消息。这一轮请换一个不同的条数（优先发 1 条），别重复同样的分条模式。"
  );
}

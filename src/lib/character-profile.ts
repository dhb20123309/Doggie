/** 首次使用时内置的两份档案（导入哪份生效哪份，互不覆盖） */
export const PRESET_PROFILES: Record<string, string> = {
  "zhou-chenyan": CHENYAN_MD,
  "zhou-fengyan": FENGYAN_MD,
};

export function presetProfileFor(charId: string): CharacterProfile | null {
  const md = PRESET_PROFILES[charId];
  if (!md) return null;
  return parseProfileMd(md, charId, "TA");
}

/* ---------- 存储：vp-phone:profiles:v1，charId → 档案，两份独立隔离 ---------- */

export function useProfiles(): [Record<string, CharacterProfile>, Setter<Record<string, CharacterProfile>>] {
  return usePersisted<Record<string, CharacterProfile>>("vp-phone:profiles:v1", {});
}

/** 读取（含首次预置补齐）：某角色档案；预置只在对应 charId 缺失时写入一次 */
export function loadProfile(
  charId: string,
  all: Record<string, CharacterProfile>
): CharacterProfile | null {
  return all[charId] ?? null;
}

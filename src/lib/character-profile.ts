export interface ProfileSection {
  key: string;
  title: string;
  /** 段落数组；基础信息类为逐行键值文本，大段文本为自然段 */
  paras: string[];
  kind: "cover" | "basic" | "text" | "warning" | "story";
}

export interface CharacterProfile {
  charId: string;
  name: string;
  /** 立绘/头像大图 data URL（上传后持久化，不用 blob URL） */
  coverUrl?: string;
  sections: ProfileSection[];
  /** 会话顶部短版开场白 */
  opener: string;
  /** 开局引子全文（一键加载到互动剧情） */
  intro: string;
  updatedAt: number;
}

const SECTION_KINDS: Record<string, ProfileSection["kind"]> = {
  封面: "cover",
  头像图: "cover",
  基础信息: "basic",
  家人信息: "basic",
  标签: "basic",
  外貌特征: "basic",
  性格内核: "basic",
  世界观: "text",
  创作者警告: "warning",
  社交账号: "text",
  朋友圈: "text",
  开局引子: "story",
  开局剧情片段: "text",
  精简开场白: "text",
};

function kindOf(title: string): ProfileSection["kind"] {
  for (const [k, v] of Object.entries(SECTION_KINDS)) if (title.includes(k)) return v;
  return "text";
}

/** 解析完整档案文本：按 ## 分节，自动识别固定区块；容错无 # 前缀的裸标题行 */
export function parseProfileMd(text: string, charId: string, fallbackName: string): CharacterProfile {
  const lines = text.split(/\r?\n/);
  const sections: ProfileSection[] = [];
  let cur: ProfileSection | null = null;
  let name = fallbackName;
  for (const raw of lines) {
    const line = raw.trimEnd();
    const m = line.match(/^#{1,3}\s*(.+?)\s*$/);
    const isBareHeading = !m && cur === null && /^[^#\->\s][^\n]{0,30}$/.test(line) && sections.length === 0;
    if (m || isBareHeading) {
      const title = (m ? m[1] : line).replace(/^人物档案｜/, "").trim();
      // 一级标题 "# 人物档案｜周晨砚（哥哥）" 兼作角色名来源
      if (m && /^#\s/.test(line) && !sections.length) {
        const nm = title.match(/^(.{2,6}?)(（|$)/);
        if (nm) name = nm[1];
      }
      if (cur) sections.push(cur);
      cur = { key: `s${sections.length}`, title, paras: [], kind: kindOf(title) };
      continue;
    }
    if (!cur) continue;
    if (!line.trim()) continue;
    cur.paras.push(line.trim().replace(/^-\s*/, ""));
  }
  if (cur) sections.push(cur);

  const findParas = (kw: string) => sections.find((s) => s.title.includes(kw))?.paras ?? [];
  const opener = findParas("精简开场白").join("\n").replace(/^>\s?/gm, "");
  const introSec = sections.find((s) => s.kind === "story");
  const intro = introSec ? introSec.paras.join("\n\n") : "";
  return { charId, name, sections, opener, intro, updatedAt: Date.now() };
}

